"""Probe-assisted closed-loop acoustic feedback cancellation.

Unlike conventional NLMS, this implementation identifies a feedback path from
an exogenous speaker probe. It uses only observed microphone samples, actual
speaker samples, and the probe generated by the device. The unknown near-end
signal and true feedback FIR are NEVER inputs to the estimator.

The path estimation is block-wise instrumental-variable identification (IV),
with optional data-derived sparse soft-thresholding (SURE). In the closed loop,
the trained FIR cancels predicted acoustic feedback sample by sample.

Assumptions: the injected probe is independent of the near-end source; a
constant linear time-invariant feedback path holds during a calibration block;
the microphone and speaker share the same sample-rate/clock; and the physical
feedback delay is represented explicitly by the sample-to-sample history.

CAUTION: A controlled simulation is not hardware safety certification. An
audio host must enforce safe gain, sample alignment, clipping protection, and
audibility constraints on the probe.
"""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np
from scipy.linalg import toeplitz


@dataclass(frozen=True)
class IdentificationResult:
    coefficients: np.ndarray
    raw_coefficients: np.ndarray
    samples: int
    probe_rms: float
    noise_std_per_tap: float
    shrinkage_threshold: float
    moment_condition: float


def _validate_series(mic: np.ndarray, loudspeaker: np.ndarray,
                     probe: np.ndarray, taps: int) -> tuple[np.ndarray, ...]:
    mic = np.asarray(mic, dtype=np.float64).ravel()
    loudspeaker = np.asarray(loudspeaker, dtype=np.float64).ravel()
    probe = np.asarray(probe, dtype=np.float64).ravel()
    if not (len(mic) == len(loudspeaker) == len(probe)):
        raise ValueError("Microphone, loudspeaker, and probe must be sample-aligned")
    if taps < 1 or len(mic) < max(20 * taps, 1024):
        raise ValueError("Insufficient calibration samples for requested FIR length")
    if not (np.all(np.isfinite(mic)) and np.all(np.isfinite(loudspeaker))
            and np.all(np.isfinite(probe))):
        raise ValueError("Nonfinite input sample")
    if np.mean(probe ** 2) < 1e-15:
        raise ValueError("A nonzero independent speaker probe is required for IV identification")
    return mic, loudspeaker, probe


def _iv_moments(mic: np.ndarray, loudspeaker: np.ndarray,
                probe: np.ndarray, taps: int) -> tuple[np.ndarray, np.ndarray]:
    """Estimate E[z x^T] and E[z mic] for x_i=u[n-i-1], z_i=p[n-i-1].

    Stationary Toeplitz approximation to the sample moment. Terms involving
    at most `taps` window-boundary samples are omitted (O(taps / N)). This
    keeps a 128-tap calibration computationally practical without a huge
    observation matrix. See README for the stationary-path limitation.
    """
    n = len(mic)
    first_col = np.array([
        np.dot(probe[:n - k], loudspeaker[k:]) for k in range(taps)
    ]) / n
    first_row = np.array([
        np.dot(probe[k:], loudspeaker[:n - k]) for k in range(taps)
    ]) / n
    moment = toeplitz(first_col, first_row)
    target = np.array([
        np.dot(probe[:n - i - 1], mic[i + 1:]) for i in range(taps)
    ]) / n
    return moment, target


def _iv_raw(mic: np.ndarray, loudspeaker: np.ndarray, probe: np.ndarray,
            taps: int, ridge_relative: float) -> tuple[np.ndarray, float]:
    moment, target = _iv_moments(mic, loudspeaker, probe, taps)
    condition = float(np.linalg.cond(moment))
    if not np.isfinite(condition) or condition > 1e6:
        raise ValueError(f"Probe identification moment is poorly conditioned ({condition:g})")
    regularization = ridge_relative * np.mean(probe ** 2)
    w = np.linalg.solve(moment + regularization * np.eye(taps), target)
    return w, condition


def _sure_soft_threshold(w: np.ndarray, sigma: float) -> tuple[np.ndarray, float]:
    """Choose a soft threshold without true path access (approximate SURE)."""
    aa = np.abs(w)
    choices = np.r_[0.0, np.unique(aa)]
    sigma2 = sigma ** 2
    risk = np.array([
        len(w) * sigma2 + np.minimum(aa * aa, t * t).sum()
        - 2 * sigma2 * np.count_nonzero(aa <= t)
        for t in choices
    ])
    threshold = float(choices[np.argmin(risk)])
    return np.sign(w) * np.maximum(aa - threshold, 0.0), threshold


def identify_path(mic: np.ndarray, loudspeaker: np.ndarray, probe: np.ndarray,
                  taps: int, *, ridge_relative: float = 1e-5,
                  sparse_shrinkage: bool = True) -> IdentificationResult:
    """Identify an acoustic path despite near-end/feedback correlation.

    No target signal or path ground truth is used. The independent injected
    probe is an instrumental variable. Splitting the record estimates the
    random coefficient error for optional SURE sparsity denoising.
    """
    mic, loudspeaker, probe = _validate_series(mic, loudspeaker, probe, taps)
    if ridge_relative < 0:
        raise ValueError("ridge_relative must be nonnegative")
    raw, cond = _iv_raw(mic, loudspeaker, probe, taps, ridge_relative)
    if sparse_shrinkage:
        mid = len(mic) // 2
        w1, _ = _iv_raw(mic[:mid], loudspeaker[:mid], probe[:mid], taps,
                         ridge_relative)
        w2, _ = _iv_raw(mic[mid:], loudspeaker[mid:], probe[mid:], taps,
                         ridge_relative)
        # Each half is twice as noisy as the full record. Independent halves
        # give Var(w1-w2) ~ 4*Var(w_full).
        noise_std = float(np.sqrt(np.mean((w1 - w2) ** 2)) / 2)
        coefficients, threshold = _sure_soft_threshold(raw, noise_std)
    else:
        coefficients = raw.copy()
        noise_std = 0.0
        threshold = 0.0
    return IdentificationResult(coefficients, raw, len(mic),
                                float(np.sqrt(np.mean(probe ** 2))),
                                noise_std, threshold, cond)


class ProbeAFC:
    """Sample-by-sample closed-loop canceller; identification runs in blocks.

    `process_mic()` is causal and processes an actual microphone sample. The
    speaker probe is added *after* the amplification/delay, making it an
    exogenous instrument. During calibration, call `identify()` to estimate
    the FIR and then `activate()` to replace the cancellation coefficients.
    """

    def __init__(self, taps: int, *, delay: int = 1, gain: float = 1.0,
                 probe_rms: float = 0.0, seed: int = 20261102):
        if taps < 1 or delay < 1:
            raise ValueError("taps and delay must be >= 1")
        if not np.isfinite(gain) or not np.isfinite(probe_rms) or probe_rms < 0:
            raise ValueError("Gain and probe RMS must be finite, probe RMS nonnegative")
        self.taps = taps
        self.delay = delay
        self.gain = gain
        self.probe_rms = probe_rms
        self.weights = np.zeros(taps)
        self.speaker_history = np.zeros(taps)
        self.error_history = np.zeros(delay)
        self.random = np.random.default_rng(seed)
        self.microphones: list[float] = []
        self.loudspeakers: list[float] = []
        self.probes: list[float] = []
        self._fade_from = self.weights.copy()
        self._fade_to = self.weights.copy()
        self._fade_total = 0
        self._fade_step = 0

    def process_mic(self, microphone: float, *, probe: float | None = None,
                    record: bool = True) -> tuple[float, float, float]:
        """Return (feedback-cancelled error, emitted speaker, emitted probe)."""
        if probe is None:
            # Bounded independent binary noise: RMS==peak==configured amplitude.
            # This avoids Gaussian probe peaks, but overall output STILL needs
            # a hardware limiter and an audible-probe level assessment.
            probe = (self.probe_rms if self.random.integers(2) else -self.probe_rms) if self.probe_rms else 0.0
        if not np.isfinite(microphone) or not np.isfinite(probe):
            raise ValueError("Nonfinite microphone or probe sample")
        if self._fade_step < self._fade_total:
            self._fade_step += 1
            fraction = self._fade_step / self._fade_total
            self.weights = (1.0 - fraction) * self._fade_from + fraction * self._fade_to
        cancellation = float(self.weights @ self.speaker_history)
        error = float(microphone - cancellation)
        forward = float(self.error_history[-1])
        speaker = self.gain * forward + probe
        if not np.isfinite(error) or not np.isfinite(speaker):
            raise FloatingPointError("Nonfinite output: stop acoustic playback")
        self.error_history[1:] = self.error_history[:-1]
        self.error_history[0] = error
        self.speaker_history[1:] = self.speaker_history[:-1]
        self.speaker_history[0] = speaker
        if record:
            self.microphones.append(float(microphone))
            self.loudspeakers.append(float(speaker))
            self.probes.append(float(probe))
        return error, float(speaker), float(probe)

    def identify(self, *, last_samples: int | None = None,
                 sparse_shrinkage: bool = True) -> IdentificationResult:
        cut = slice(-last_samples, None) if last_samples is not None else slice(None)
        return identify_path(np.asarray(self.microphones)[cut],
                             np.asarray(self.loudspeakers)[cut],
                             np.asarray(self.probes)[cut], self.taps,
                             sparse_shrinkage=sparse_shrinkage)

    def activate(self, result: IdentificationResult, *, fade_samples: int = 0) -> None:
        if result.coefficients.shape != (self.taps,):
            raise ValueError("Path estimate length mismatch")
        if not np.all(np.isfinite(result.coefficients)):
            raise ValueError("Nonfinite path estimate")
        if fade_samples < 0:
            raise ValueError("fade_samples cannot be negative")
        self._fade_from = self.weights.copy()
        self._fade_to = result.coefficients.copy()
        self._fade_total = fade_samples
        self._fade_step = 0
        if fade_samples == 0:
            self.weights = result.coefficients.copy()

    def clear_recorded_audio(self) -> None:
        """Free calibration history without clearing the active filter/state."""
        self.microphones.clear()
        self.loudspeakers.clear()
        self.probes.clear()


class FIRFeedbackPlant:
    """Known true acoustic path, for TESTS only. Never passed to identify_path."""

    def __init__(self, true_path: np.ndarray):
        self.true_path = np.asarray(true_path, dtype=np.float64).ravel()
        self.speaker_history = np.zeros(len(self.true_path))

    def microphone(self, source: float) -> float:
        return float(source + self.true_path @ self.speaker_history)

    def observe_speaker(self, speaker: float) -> None:
        self.speaker_history[1:] = self.speaker_history[:-1]
        self.speaker_history[0] = speaker


def accuracy(true_path: np.ndarray, estimate: np.ndarray,
             fft_size: int = 16384) -> dict[str, float]:
    """Simulation-only scoring: never use this inside the real canceller."""
    true_path = np.asarray(true_path, dtype=np.float64).ravel()
    estimate = np.asarray(estimate, dtype=np.float64).ravel()
    delta = true_path - estimate
    nfce = float((delta @ delta) / (true_path @ true_path))
    f0 = np.fft.rfft(true_path, fft_size)
    ferr = np.fft.rfft(delta, fft_size)
    msg0 = float(-20 * np.log10(np.max(abs(f0))))
    residual_peak = float(np.max(abs(ferr)))
    msg = float('inf') if residual_peak == 0 else float(-20 * np.log10(residual_peak))
    return {"nfce": nfce, "msg0_db": msg0, "msg_db": msg,
            "asg_db": msg - msg0}
